import { describe, expect, it } from 'vitest';
import { ADAPT_INSTRUCTIONS, ADAPT_MAX_CODE, cleanAdaptedCode } from '../lib/adaptPrompt';
import { checkAdaptedSource } from '../lib/shotAdapter';
import fs from 'node:fs';
import path from 'node:path';

describe('adapt prompt output', () => {
  it('strips markdown fences and refuses empty or oversized code', () => {
    expect(cleanAdaptedCode('```tsx\nexport default () => null\n```')).toBe('export default () => null');
    expect(cleanAdaptedCode('  export default () => null  ')).toBe('export default () => null');
    expect(cleanAdaptedCode('')).toBeNull();
    expect(cleanAdaptedCode(42)).toBeNull();
    expect(cleanAdaptedCode('x'.repeat(ADAPT_MAX_CODE + 1))).toBeNull();
  });

  it('tells the agent the upstream rules', () => {
    for (const phrase of ['easing', 'pitfalls', 'Math.random', 'exports exactly', 'Never invent']) expect(ADAPT_INSTRUCTIONS).toContain(phrase);
  });
});

describe('recipes as shipped to the adapter', () => {
  it('every published recipe is plain TSX the sandbox can read (imports are the only blockers)', async () => {
    const dir = path.resolve('public/motion-studio/sources');
    if (!fs.existsSync(dir)) return; // generated by `npm run gen:demo-sources`
    const names = fs.readdirSync(dir).filter((f) => f.endsWith('.tsx.txt'));
    expect(names.length).toBeGreaterThan(0);
    const blocked: string[] = [];
    let passed = 0;
    for (const n of names) {
      const r = await checkAdaptedSource(fs.readFileSync(path.join(dir, n), 'utf8'));
      if (!r.ok) blocked.push(`${n}: ${r.error}`);
      else passed++;
    }
    // Originals read JSON layouts, make canvases, etc., which the agent must replace with props; none may be a parse failure.
    expect(blocked.filter((b) => /syntax/.test(b))).toEqual([]);
    expect(passed + blocked.length).toBe(names.length);
    expect(passed).toBeGreaterThan(names.length * 0.3);
  });
});
