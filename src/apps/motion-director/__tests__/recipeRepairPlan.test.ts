// @vitest-environment jsdom
/**
 * Writes docs/motion-director-pipeline-audit/RECIPE-REPAIR-PLAN.md: for every recipe that is not "tested", what exactly is missing,
 * from the measured sweep (lib/_generated/recipeSweepResults.json) and the recipe's own source. Run: GEN_PLAN=1 npx vitest run src/apps/motion-director/__tests__/recipeRepairPlan.test.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { MOTION_TEMPLATES } from '@/data/motionRecipeCatalog';
import { DEMO_TEXTS } from '../demosrc/_generated/demoTexts';
import { recipeContract, contractSummary } from '../lib/recipeContract';
import { fallbackTexts, neutralTexts } from '../lib/retext';
import { SWEEP_CONTENT } from '../lib/recipeSweep';
import { isProductTextureShot } from '../lib/productShots';
import { GEOMETRY_UNMAPPED, LAYOUT_NEEDS } from '../lib/buildFilm';
import reads from '../lib/_generated/recipeReads.json';

const READS = reads as unknown as Record<string, { brand: boolean; textures: boolean; fixtures: boolean }>;
const stems = MOTION_TEMPLATES.map((t) => t.componentName).filter((s, i, a) => a.indexOf(s) === i);
const rows = stems.map((s) => ({ c: recipeContract(s), t: MOTION_TEMPLATES.find((m) => m.componentName === s)! }));
const sum = contractSummary();

const kindOf = (line: string) => (/\d/.test(line) ? 'a figure or dated claim' : /^[A-Z][a-z]+( [A-Z][a-z]+)?$/.test(line) ? 'a name or label' : 'copy');
const left = (stem: string) => {
  const strings = DEMO_TEXTS[stem] ?? [];
  const done = { ...fallbackTexts(strings, SWEEP_CONTENT, 'Acme', { index: 0, headline: 'Acme ships faster', caption: 'Plan in minutes' }), ...neutralTexts(strings, 'Acme', { sitePages: false, hasPictures: true }) };
  return strings.filter((l) => !(l in done));
};

const lines: string[] = [];
lines.push('# Recipe repair plan (generated)', '', 'Generated by `GEN_PLAN=1 npx vitest run src/apps/motion-director/__tests__/recipeRepairPlan.test.ts` from the measured sweep (`lib/_generated/recipeSweepResults.json`) and each recipe\'s own source. Nothing here is guessed: a recipe is "tested" only when frames showed the person\'s material.', '');
lines.push('## Totals', '', '| State | Recipes |', '|---|---|', `| tested (the person's pictures, words or brand were seen in rendered frames) | ${sum.tested} |`, `| partly (some of its own copy stays the sample's) | ${sum.partly} |`, `| sample-only (has sample content, none of it replaced) | ${sum.sampleOnly} |`, `| not-applicable (draws nothing of its own to replace) | ${sum.notApplicable} |`, `| untested / not rendering | ${sum.untested} (${sum.notRenderable} not renderable) |`, `| **total** | **${sum.total}** |`, '');
lines.push('Layout-dependent recipes (read the page\'s geometry): retargeted onto the customer\'s own cards/rows: ' + Object.keys(LAYOUT_NEEDS).join(', ') + '. Not retargeted: ' + Object.entries(GEOMETRY_UNMAPPED).map(([k, v]) => `${k} (${v})`).join('; ') + '.', '');
for (const state of ['partly', 'sample-only', 'not-applicable', 'untested'] as const) {
  const set = rows.filter((r) => r.c.personalizable === state);
  lines.push(`## ${state} (${set.length})`, '', '| Recipe | Category | Reads | Own lines | Replaced | What stays the sample\'s | Basis |', '|---|---|---|---|---|---|---|');
  for (const { c, t } of set) {
    const r = READS[c.stem] ?? { brand: false, textures: false, fixtures: false };
    const kinds = [r.brand ? 'brand' : '', r.textures || isProductTextureShot(c.stem) ? 'pictures' : '', r.fixtures ? 'sample UI' : ''].filter(Boolean).join(', ') || 'nothing';
    const l = left(c.stem);
    const stay = l.length ? `${l.length} lines: ${l.slice(0, 4).map((x) => `"${x.slice(0, 28)}"`).join(', ')}${l.length > 4 ? ', …' : ''} (${[...new Set(l.map(kindOf))].join('/')})` : state === 'partly' ? 'its picture area' : '—';
    lines.push(`| ${c.stem} | ${t.category} | ${kinds} | ${(DEMO_TEXTS[c.stem] ?? []).length} | ${(DEMO_TEXTS[c.stem] ?? []).length - l.length} | ${stay} | ${c.basis} |`);
  }
  lines.push('');
}
import { it } from 'vitest';
it.runIf(process.env.GEN_PLAN === '1')('writes the repair plan', () => {
const out = path.resolve('docs/motion-director-pipeline-audit/RECIPE-REPAIR-PLAN.md');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}: ${JSON.stringify(sum)}`);
});
