#!/usr/bin/env node
/**
 * Lists the words each Motion Director recipe draws (JSX text and string literals that read
 * as words), so a person or the AI can rewrite them: `demosrc/_generated/demoTexts.ts`.
 * Run `npm run gen:demo-texts` after editing a recipe; the output is committed.
 */
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const ROOT = path.resolve('src/apps/motion-director/demosrc')
const OUT = path.join(ROOT, '_generated', 'demoTexts.ts')

const CSS_WORD = /^(?:flex|grid|block|none|auto|center|absolute|relative|fixed|hidden|visible|bold|normal|italic|inherit|transparent|white|black|solid|dashed|dotted|nowrap|wrap|column|row|left|right|top|bottom|middle|start|end|cover|contain|pointer|default|text|round|square|butt|miter|bevel|uppercase|lowercase|capitalize|ease|linear|circle|ellipse|clip|svg|path|rect|line|g|div|span|img|button|input|use|mask|defs|filter|stop|linearGradient|radialGradient|clipPath|polygon|polyline)$/i
const CSS_LIKE = /(?:\d(?:px|em|rem|vh|vw|deg|ms|s)\b|%|#[0-9a-f]{3,8}\b|rgba?\(|hsla?\(|gradient|url\(|calc\(|cubic-bezier|translate|rotate|scale\(|blur\(|inset|^\s*[\d.\s,-]+$|^[\w-]+\/[\w./-]+$|^https?:|\.(?:png|jpe?g|svg|mp3|mp4|webp)\b|^[a-z]+(?:-[a-z]+)+$|^[a-z]+[A-Z]\w*$|^[A-Z][a-z]+[A-Z]\w*$|^[A-Z_]{2,}_[A-Z_]+$)/
const CODE_LIKE = /sans-serif|monospace|system-ui|\bHelvetica\b|\bImpact\b|[<>{}=;]|\b[a-z][\w-]*\([^)]*\)|^(?:export|function|const|return|import)\b|\(props|&nbsp;/
const WORDY = /[A-Za-zÀ-ɏ぀-ヿ一-鿿]{2}/

const HEX = /^\s*#[0-9a-f]{3,8}\s*$/i
const looksLikeWords = (raw) => {
  const s = raw.replace(/\s+/g, ' ').trim()
  if (s.length < 2 || s.length > 120) return null
  if (CODE_LIKE.test(s) || HEX.test(s) || /#[0-9a-f]{6}/i.test(s) || !WORDY.test(s) || CSS_LIKE.test(s) || CSS_WORD.test(s)) return null
  if (!/\s/.test(s) && /^[a-z0-9]+$/.test(s)) return null // a bare lowercase token is almost always an identifier
  return s
}

const files = []
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (e.name !== '_fixtures' && e.name !== '_generated' && e.name !== '_legacy') walk(p)
    } else if (e.name.endsWith('.tsx')) files.push(p)
  }
}
walk(ROOT)

const out = {}
for (const file of files.sort()) {
  const src = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const seen = new Set()
  const list = []
  const add = (raw) => {
    const s = looksLikeWords(raw)
    if (s && !seen.has(s.toLowerCase())) {
      seen.add(s.toLowerCase())
      list.push(s)
    }
  }
  const visit = (node) => {
    if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node) || ts.isTypeNode(node) || ts.isLiteralTypeNode(node)) return
    if (ts.isJsxText(node)) add(node.getText())
    else if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      const parent = node.parent
      // Style, class, id, geometry and path attributes are not words.
      if (ts.isJsxAttribute(parent) && !['alt', 'title', 'label', 'placeholder', 'aria-label'].includes(parent.name.getText())) return
      if (ts.isPropertyAssignment(parent) && parent.initializer === node && /^(?:fontFamily|fontWeight|fontStyle|background\w*|color|border\w*|boxShadow|transform\w*|transition|filter|mixBlendMode|textTransform|textAlign|whiteSpace|display|position|overflow|cursor|opacity|outline|content|d|fill|stroke\w*|viewBox|href|src|type|kind|mode|variant|align\w*|justify\w*)$/.test(parent.name.getText())) return
      if (ts.isElementAccessExpression(parent) || ts.isCaseClause(parent) || ts.isBinaryExpression(parent) && ['===', '!==', '==', '!='].includes(parent.operatorToken.getText())) return
      add(node.text)
    }
    ts.forEachChild(node, visit)
  }
  visit(src)
  if (list.length) out[path.basename(file, '.tsx')] = list
}

const body = `// Generated by scripts/gen-demo-texts.mjs — do not edit by hand.\n/** The words each recipe draws, by component name (source order, de-duplicated). */\nexport const DEMO_TEXTS: Record<string, readonly string[]> = ${JSON.stringify(out, null, 1)}\n`
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, body)
console.log(`demo texts: ${Object.keys(out).length} recipes, ${Object.values(out).reduce((n, l) => n + l.length, 0)} strings`)
