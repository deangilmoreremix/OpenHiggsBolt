/**
 * Writes src/data/nicheDemos.generated.ts: the demos each landing page
 * industry section shows, resolved from the full demo catalogs in
 * src/data/nicheDemoSource.ts. The landing page imports only the generated
 * file, so it no longer ships the 2.7 MB Seedance 2.0 prompt catalog.
 *
 * Run after changing nicheDemoSource.ts or any demo catalog it reads:
 *   npm run generate:niche-demos
 * src/data/__tests__/nicheDemos.test.ts fails while the file is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SOURCE_NICHE_IDS, resolveDemosForNiche } from '../src/data/nicheDemoSource';

const out = fileURLToPath(new URL('../src/data/nicheDemos.generated.ts', import.meta.url));
const byNiche = Object.fromEntries(SOURCE_NICHE_IDS.map((id) => [id, resolveDemosForNiche(id)]));

writeFileSync(
  out,
  `// GENERATED by scripts/generate-niche-demos.ts from src/data/nicheDemoSource.ts.
// Do not edit by hand: run \`npm run generate:niche-demos\`.
import { type VideoDemo } from './types';

export const NICHE_DEMOS: Record<string, VideoDemo[]> = ${JSON.stringify(byNiche, null, 2)};
`,
);

const total = Object.values(byNiche).reduce((n, list) => n + list.length, 0);
console.log(`Wrote ${total} demos for ${SOURCE_NICHE_IDS.length} niches to ${out}`);
