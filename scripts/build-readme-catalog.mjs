#!/usr/bin/env node
// Keeps README.md in step with the studios and features the app actually ships.
//
// Source of truth:
//   - src/data/studioKnowledgeBase.json   every studio: name, route, description, key features
//   - components/StandaloneShell.js TABS  the studio tab bar (order, and a coverage check)
//   - docs/features/README.md             the generated feature registry (one page per feature)
//
// Rewrites two blocks of README.md (between the marker comments):
//   <!-- STUDIO-CATALOG:START --> ... <!-- STUDIO-CATALOG:END -->
//   <!-- FEATURE-REGISTRY:START --> ... <!-- FEATURE-REGISTRY:END -->
// and fails (--check: writes nothing, exits 1) when
//   - README.md is out of date, or
//   - a studio tab has neither a knowledge-base entry nor an entry in TAB_ONLY below, or
//   - an app/ page route or apps/ folder is not named in README.md.
//
// Usage: node scripts/build-readme-catalog.mjs [--check]
// Run `node scripts/build-feature-index.mjs` first when you added a docs/features page.
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const check = process.argv.includes('--check');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

// Studio tabs that have no studioKnowledgeBase.json entry yet. Add the knowledge-base entry
// and delete the row here when you can; until then the row keeps the README honest.
const TAB_ONLY = {
  'media-hub': { name: 'Smartvid Downloader', route: '/studio/media-hub', summary: 'Download videos and audio from links, with transcripts, AI summaries and subscriptions. A vendored web edition of VidBee (see apps/smartvid/UPSTREAM.md).' },
};

const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const clip = (s, n) => { const t = cell(s); return t.length > n ? `${t.slice(0, n - 1).trimEnd()}…` : t; };
const firstSentences = (s, n) => {
  const t = cell(s);
  const parts = t.match(/[^.!?]+[.!?]+(?=\s|$)/g) || [t];
  let out = '';
  for (const p of parts) { if ((out + p).length > n) break; out += `${out ? ' ' : ''}${p.trim()}`; }
  return out || clip(t, n);
};

// ---- studios ----
const kb = JSON.parse(read('src/data/studioKnowledgeBase.json')).studios;
const kbById = new Map(kb.map((s) => [s.id, s]));
const shell = read('components/StandaloneShell.js');
const tabsBlock = shell.match(/const TABS = \[([\s\S]*?)\];/);
const tabIds = tabsBlock ? [...tabsBlock[1].matchAll(/\{\s*id:\s*'([\w-]+)'/g)].map((m) => m[1]) : [];

const problems = [];
if (!tabIds.length) problems.push('components/StandaloneShell.js: could not read the TABS list');

const studios = [];
for (const id of tabIds) {
  const s = kbById.get(id);
  if (s) studios.push({ id, name: s.name, route: s.route, summary: s.shortDescription, features: s.keyFeatures || [] });
  else if (TAB_ONLY[id]) studios.push({ id, ...TAB_ONLY[id], features: [] });
  else problems.push(`studio tab "${id}" has no entry in src/data/studioKnowledgeBase.json (add one, or add it to TAB_ONLY in scripts/build-readme-catalog.mjs)`);
}
for (const s of kb) { // standalone studios that are not tabs (Photo Studio, Video Pages, Social Publishing...)
  if (!tabIds.includes(s.id)) studios.push({ id: s.id, name: s.name, route: s.route, summary: s.shortDescription, features: s.keyFeatures || [] });
}

function studioBlock() {
  const out = [
    `**${studios.length} studios and tools**, all powered by the shared \`packages/studio\` library and 200+ Muapi models. Most open at \`/studio/<id>\`; a few (Brand Studio, Photo Studio) have their own page.`,
    '',
    '_This block is generated by `npm run docs:readme` from `src/data/studioKnowledgeBase.json` and the studio tab bar. Do not edit it by hand: update the knowledge-base entry (or add a `docs/features/` page) and re-run the script._',
    '',
    '| Studio | Route | What it does |',
    '| :--- | :--- | :--- |',
  ];
  for (const s of studios) out.push(`| **${cell(s.name)}** | \`${s.route}\` | ${firstSentences(s.summary, 260)} |`);
  out.push('', '<details>', '<summary><b>Every studio\'s key features</b></summary>', '');
  for (const s of studios) {
    if (!s.features.length) continue;
    out.push(`#### ${cell(s.name)} (\`${s.route}\`)`, '');
    for (const f of s.features) out.push(`- ${clip(f, 320)}`);
    out.push('');
  }
  out.push('</details>');
  return out.join('\n');
}

// ---- feature registry ----
function registryBlock() {
  const reg = read('docs/features/README.md');
  const rows = reg.split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| Feature ') && !l.startsWith('|---'));
  const out = [
    `**${rows.length} documented features** (one page each in [docs/features](docs/features/README.md)). Add a page for every new user-facing feature (see \`AGENTS.md\`).`,
    '',
    '| Feature | Area | Status | Where in app | Added | Details |',
    '|---|---|---|---|---|---|',
    ...rows.map((l) => l.replace(/\]\(([^)]+)\)/, '](docs/features/$1)')),
  ];
  return out.join('\n');
}

function withBlock(text, name, body) {
  const start = `<!-- ${name}:START -->`;
  const end = `<!-- ${name}:END -->`;
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a === -1 || b === -1 || b < a) throw new Error(`README.md: missing ${start} / ${end} markers`);
  return `${text.slice(0, a + start.length)}\n${body}\n${text.slice(b)}`;
}

const readme = read('README.md');
const wanted = withBlock(withBlock(readme, 'STUDIO-CATALOG', studioBlock()), 'FEATURE-REGISTRY', registryBlock());

// ---- coverage: page routes and apps/ folders must be named in the README ----
const wantedLower = wanted.toLowerCase();
const appTop = fs.readdirSync(path.join(root, 'app'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_') && !['api', 'actions'].includes(d.name))
  .map((d) => d.name.replace(/^\((.*)\)$/, '$1')); // route groups: (brand-studio) -> brand-studio
const groupChildren = fs.existsSync(path.join(root, 'app/(brand-studio)'))
  ? fs.readdirSync(path.join(root, 'app/(brand-studio)'), { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name) : [];
for (const name of [...appTop.filter((n) => n !== 'brand-studio'), ...groupChildren]) {
  if (!wantedLower.includes(`/${name.toLowerCase()}`)) problems.push(`page route /${name} (app/${name}) is not named in README.md: add it to "Beyond the studio shell"`);
}
for (const d of fs.readdirSync(path.join(root, 'apps'), { withFileTypes: true })) {
  if (d.isDirectory() && !wanted.includes(`apps/${d.name}`)) problems.push(`apps/${d.name} is not named in README.md: add it to "Bundled apps"`);
}

if (wanted !== readme) {
  if (check) problems.push('README.md is out of date: run `npm run docs:readme`');
  else { fs.writeFileSync(path.join(root, 'README.md'), wanted); console.log('[docs:readme] wrote README.md'); }
}
if (problems.length) {
  console.error(`[docs:readme] ${problems.length} problem(s):\n- ${problems.join('\n- ')}`);
  process.exit(1);
}
console.log(`[docs:readme] ${check ? 'up to date' : 'done'} (${studios.length} studios, ${wanted.split('\n').filter((l) => /^\| .*\]\(docs\/features\//.test(l)).length} feature pages)`);
