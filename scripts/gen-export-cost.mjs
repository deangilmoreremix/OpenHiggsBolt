#!/usr/bin/env node
/**
 * Turns benchmark results (JSON lines of {name, ms, frames}) into `demosrc/_generated/exportCost.ts`:
 * the measured web-renderer time per frame of each recipe. See scripts/export-bench/README.md.
 *   node scripts/gen-export-cost.mjs results-0.jsonl results-1.jsonl ...
 */
import fs from 'node:fs'
import path from 'node:path'

const OVERHEAD_MS = 1200 // fixed cost of one render (encoder and scaffold set-up), not per frame
const files = process.argv.slice(2)
if (!files.length) {
  console.error('usage: gen-export-cost.mjs results.jsonl ...')
  process.exit(1)
}
const table = {}
for (const f of files) {
  for (const line of fs.readFileSync(f, 'utf8').split('\n').filter(Boolean)) {
    const r = JSON.parse(line)
    if (typeof r.ms !== 'number' || !r.frames) continue
    // A render stopped at the time limit only says "at least this slow".
    table[r.name] = Math.max(20, Math.round(Math.max(0, r.ms - OVERHEAD_MS) / r.frames / 10) * 10)
  }
}
const sorted = Object.fromEntries(Object.entries(table).sort(([a], [b]) => a.localeCompare(b)))
const out = path.resolve('src/apps/motion-director/demosrc/_generated/exportCost.ts')
fs.writeFileSync(out, `// Generated by scripts/gen-export-cost.mjs from scripts/export-bench results — do not edit by hand.\n/** Measured web-renderer milliseconds per frame (1080p, one headless Chromium core) by recipe component name. */\nexport const EXPORT_MS_PER_FRAME: Record<string, number> = ${JSON.stringify(sorted, null, 1)}\n`)
console.log(`export cost: ${Object.keys(sorted).length} recipes`)
