#!/usr/bin/env node
/**
 * The two checklists the independent final review uses (upstream pipeline stage 7), from the English
 * docs: final-review.md (its check items P/F/V/S/B/D/A/Q and report format, in full) and the rules of
 * aesthetic-rules.md (each rule's ID, heading and "Rule:" line). Output is committed:
 * src/apps/motion-director/lib/_generated/reviewChecklists.ts. Run after the docs change.
 */
import fs from 'node:fs'
import path from 'node:path'

const DOCS = path.resolve('docs/video-shotcraft-en/references')
const final = fs.readFileSync(path.join(DOCS, 'final-review.md'), 'utf8')
const from = final.indexOf('## Check items')
const finalReview = (from >= 0 ? final.slice(from) : final).trim()
const aesthetic = fs.readFileSync(path.join(DOCS, 'aesthetic-rules.md'), 'utf8')
const rules = []
const lines = aesthetic.split('\n')
for (let i = 0; i < lines.length; i++) {
  const h = lines[i].match(/^### ([A-Z]\d+)\. (.+)$/)
  if (!h) continue
  const rule = lines.slice(i + 1, i + 4).find((l) => l.startsWith('Rule:')) ?? ''
  rules.push(`${h[1]}. ${h[2]}\n  ${rule.replace(/^Rule:\s*/, '').replace(/\*\*/g, '')}`)
}
const OUT = path.resolve('src/apps/motion-director/lib/_generated/reviewChecklists.ts')
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, `// Generated by scripts/gen-review-checklists.mjs from docs/video-shotcraft-en — do not edit by hand.\n/** final-review.md: check items P/F/V/S/B/D/A/Q and the report format. */\nexport const FINAL_REVIEW = ${JSON.stringify(finalReview)};\n/** aesthetic-rules.md: every rule's ID, heading and rule line. */\nexport const AESTHETIC_RULES = ${JSON.stringify(rules.join('\n'))};\n`)
console.log(`review checklists: final-review ${finalReview.length} chars, ${rules.length} aesthetic rules`)
