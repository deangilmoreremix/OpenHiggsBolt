#!/usr/bin/env node
/**
 * Facts about each Motion Director recipe, read from the upstream shot cards and the
 * polish notes, for the director's rules (`lib/shotRules.ts`): the card name, the visual
 * look the recipe was designed in (dark / light family), its energy, whether it needs
 * sound to read, and whether it is a technique card without native length.
 * Output: `demosrc/_generated/shotFacts.ts`. Run `npm run gen:shot-facts` after the skill
 * cards change; the output is committed.
 */
import fs from 'node:fs'
import path from 'node:path'

const SKILL = path.resolve('.claude/skills/video-shotcraft')
const CATALOG = fs.readFileSync(path.resolve('src/data/motionRecipeCatalog.ts'), 'utf8')
const OUT = path.resolve('src/apps/motion-director/demosrc/_generated/shotFacts.ts')

const cards = new Map()
for (const dir of fs.readdirSync(path.join(SKILL, 'references/shots'), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue
  for (const f of fs.readdirSync(path.join(SKILL, 'references/shots', dir.name))) {
    if (f.endsWith('.md') && f !== 'ATTRIBUTION.md') cards.set(f.slice(0, -3), fs.readFileSync(path.join(SKILL, 'references/shots', dir.name, f), 'utf8'))
  }
}

// The English cards (docs/video-shotcraft-en, translated in full) give the director its catalog lines.
const EN = path.resolve('docs/video-shotcraft-en/references/shots')
const english = new Map()
if (fs.existsSync(EN)) {
  for (const dir of fs.readdirSync(EN, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue
    for (const f of fs.readdirSync(path.join(EN, dir.name))) if (f.endsWith('.md')) english.set(f.slice(0, -3), fs.readFileSync(path.join(EN, dir.name, f), 'utf8'))
  }
}
const clip = (s, n) => (s.length > n ? `${s.slice(0, n - 1).replace(/[\s,;:]+\S*$/, '')}…` : s)

/** The card's "Known pitfalls" bullets (the values that must not be downgraded), first lines, clipped. */
const pitfallsOf = (md) => {
  const sec = md.split(/\n(?=## )/).find((x) => /^## Known pitfalls/.test(x)) ?? ''
  return sec.split('\n').filter((l) => /^\s*- /.test(l)).map((l) => clip(l.replace(/^\s*- /, '').replace(/\*\*/g, '').trim(), 220)).slice(0, 6)
}

const front = (md, key) => md.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim() ?? ''
const energyOf = (raw) => {
  if (!raw || /^n\/a/i.test(raw)) return 'n/a'
  if (/^极高|^高/.test(raw)) return 'high'
  if (/^中高/.test(raw)) return 'mid-high'
  if (/^中低|^低中/.test(raw)) return 'low-mid'
  if (/^中/.test(raw)) return 'mid'
  if (/^低/.test(raw)) return 'low'
  if (/^A 高|^A 中高/.test(raw)) return 'high'
  return 'mid'
}

// The recipe sources: does a recipe draw in the Look roles (re-skinned by LOOKS), or in colours of its own (repainted by lib/themePaint)?
const DEMOSRC = path.resolve('src/apps/motion-director/demosrc')
const sourceOf = new Map()
for (const cat of fs.readdirSync(DEMOSRC, { withFileTypes: true })) {
  if (!cat.isDirectory() || cat.name.startsWith('_')) continue
  for (const shot of fs.readdirSync(path.join(DEMOSRC, cat.name), { withFileTypes: true })) {
    if (!shot.isDirectory()) continue
    for (const f of fs.readdirSync(path.join(DEMOSRC, cat.name, shot.name))) if (f.endsWith('.tsx')) sourceOf.set(f.slice(0, -4), fs.readFileSync(path.join(DEMOSRC, cat.name, shot.name, f), 'utf8'))
  }
}
// Grounds of the recipes in a palette of their own, measured once from their reference frames.
const MEASURED = JSON.parse(fs.readFileSync(path.resolve('scripts/recipe-grounds.json'), 'utf8'))
const DARK_LOOKS = new Set(['midnight', 'aurora', 'ember', 'graphite', 'lime'])

const facts = {}
const re = /slug: '([^']+)',\s*componentName: '([^']+)'/g
for (let m; (m = re.exec(CATALOG)); ) {
  const [, slug, component] = m
  const md = cards.get(slug)
  if (!md) throw new Error(`no shot card for ${slug}`)
  const notePath = path.join(SKILL, 'shot-polish/notes', `${component}.json`)
  const look = fs.existsSync(notePath) ? JSON.parse(fs.readFileSync(notePath, 'utf8')).look ?? 'custom' : 'custom'
  facts[component] = {
    slug,
    look,
    energy: energyOf(front(md, '能量')),
    sound: /声音强依赖|声音强依赖手法|无声版/.test(md),
    technique: /^时长:\s*n\/a/m.test(md),
    oneLiner: clip(front(english.get(slug) ?? '', 'one_liner'), 170),
    useWhen: clip(front(english.get(slug) ?? '', 'use_when'), 130),
    energyText: clip(front(english.get(slug) ?? '', 'energy'), 90),
    pitfalls: pitfallsOf(english.get(slug) ?? ''),
    ground: look === 'custom' ? MEASURED[component] ?? 'dark' : DARK_LOOKS.has(look) ? 'dark' : 'light',
    readsLook: /\bLOOKS\b|designedLook/.test(sourceOf.get(component) ?? ''),
  }
}
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, `// Generated by scripts/gen-shot-facts.mjs from the upstream shot cards — do not edit by hand.\nexport interface ShotFacts {\n  /** The upstream card (references/shots/<category>/<slug>.md). */\n  slug: string\n  /** The Look the recipe was designed in (shot-polish notes); 'custom' = its own palette. */\n  look: 'midnight' | 'aurora' | 'ember' | 'graphite' | 'lime' | 'paper' | 'porcelain' | 'sand' | 'custom'\n  energy: 'low' | 'low-mid' | 'mid' | 'mid-high' | 'high' | 'n/a'\n  /** The card says it needs its sound to read. */\n  sound: boolean\n  /** A technique card: no native length of its own. */\n  technique: boolean\n  /** The English card's one-line description (what the shot looks like). */\n  oneLiner: string\n  /** When the English card says to use it. */\n  useWhen: string\n  /** The English card's energy line. */\n  energyText: string\n  /** The English card's known pitfalls (never downgraded; checked in the review). */\n  pitfalls: string[]\n  /** The ground the recipe was designed on. */\n  ground: 'dark' | 'light'\n  /** It draws in the Look roles (LOOKS re-skins it); otherwise lib/themePaint repaints its own colours. */\n  readsLook: boolean\n}\nexport const SHOT_FACTS: Record<string, ShotFacts> = ${JSON.stringify(facts, null, 1)} as Record<string, ShotFacts>\n`)
console.log(`shot facts: ${Object.keys(facts).length} recipes`)
