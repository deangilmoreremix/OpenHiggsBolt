#!/usr/bin/env node
/**
 * Facts about each Motion Director recipe, read from the upstream shot cards and the
 * polish notes, for the director's rules (`lib/shotRules.ts`): the card name, the visual
 * look the recipe was designed in (dark / light family), its energy, whether it needs
 * sound to read, and whether it is a technique card without native length.
 * Output: `demosrc/_generated/shotFacts.ts`. Run `npm run gen:shot-facts` after the skill
 * cards change; the output is committed.
 */
import fs from 'node:fs'
import path from 'node:path'

const SKILL = path.resolve('.claude/skills/video-shotcraft')
const CATALOG = fs.readFileSync(path.resolve('src/data/motionRecipeCatalog.ts'), 'utf8')
const OUT = path.resolve('src/apps/motion-director/demosrc/_generated/shotFacts.ts')

const cards = new Map()
for (const dir of fs.readdirSync(path.join(SKILL, 'references/shots'), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue
  for (const f of fs.readdirSync(path.join(SKILL, 'references/shots', dir.name))) {
    if (f.endsWith('.md') && f !== 'ATTRIBUTION.md') cards.set(f.slice(0, -3), fs.readFileSync(path.join(SKILL, 'references/shots', dir.name, f), 'utf8'))
  }
}

const front = (md, key) => md.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim() ?? ''
const energyOf = (raw) => {
  if (!raw || /^n\/a/i.test(raw)) return 'n/a'
  if (/^极高|^高/.test(raw)) return 'high'
  if (/^中高/.test(raw)) return 'mid-high'
  if (/^中低|^低中/.test(raw)) return 'low-mid'
  if (/^中/.test(raw)) return 'mid'
  if (/^低/.test(raw)) return 'low'
  if (/^A 高|^A 中高/.test(raw)) return 'high'
  return 'mid'
}

const facts = {}
const re = /slug: '([^']+)',\s*componentName: '([^']+)'/g
for (let m; (m = re.exec(CATALOG)); ) {
  const [, slug, component] = m
  const md = cards.get(slug)
  if (!md) throw new Error(`no shot card for ${slug}`)
  const notePath = path.join(SKILL, 'shot-polish/notes', `${component}.json`)
  const look = fs.existsSync(notePath) ? JSON.parse(fs.readFileSync(notePath, 'utf8')).look ?? 'custom' : 'custom'
  facts[component] = {
    slug,
    look,
    energy: energyOf(front(md, '能量')),
    sound: /声音强依赖|声音强依赖手法|无声版/.test(md),
    technique: /^时长:\s*n\/a/m.test(md),
  }
}
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, `// Generated by scripts/gen-shot-facts.mjs from the upstream shot cards — do not edit by hand.\nexport interface ShotFacts {\n  /** The upstream card (references/shots/<category>/<slug>.md). */\n  slug: string\n  /** The Look the recipe was designed in (shot-polish notes); 'custom' = its own palette. */\n  look: 'midnight' | 'aurora' | 'ember' | 'graphite' | 'lime' | 'paper' | 'porcelain' | 'sand' | 'custom'\n  energy: 'low' | 'low-mid' | 'mid' | 'mid-high' | 'high' | 'n/a'\n  /** The card says it needs its sound to read. */\n  sound: boolean\n  /** A technique card: no native length of its own. */\n  technique: boolean\n}\nexport const SHOT_FACTS: Record<string, ShotFacts> = ${JSON.stringify(facts, null, 1)} as Record<string, ShotFacts>\n`)
console.log(`shot facts: ${Object.keys(facts).length} recipes`)
