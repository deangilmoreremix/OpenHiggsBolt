#!/usr/bin/env node
/**
 * Where each sound effect's energy peaks, and how loud it is, so a sound can be pinned by its
 * PEAK on the frame it belongs to (upstream sound-design §4.6: pin = target peak frame − the
 * file's peak lag − the output's audio offset). Needs ffmpeg. Output:
 * `src/apps/motion-director/demosrc/_generated/sfxPeaks.ts`; run `npm run gen:sfx-peaks`.
 */
import { execFileSync, spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve('public/motion-studio/sfxlib')
const OUT = path.resolve('src/apps/motion-director/demosrc/_generated/sfxPeaks.ts')
const RATE = 8000
const table = {}
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p)
    else if (e.name.endsWith('.mp3')) {
      const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', p, '-ac', '1', '-ar', String(RATE), '-f', 'f32le', '-'], { maxBuffer: 1 << 28 })
      const x = new Float32Array(raw.buffer, raw.byteOffset, Math.floor(raw.byteLength / 4))
      // Peak position of a 5 ms smoothed envelope (a single hot sample is not "where the sound is").
      const win = Math.round(RATE * 0.005)
      let best = 0, bestAt = 0, peak = 0
      let acc = 0
      for (let i = 0; i < x.length; i++) {
        const a = Math.abs(x[i])
        if (a > peak) peak = a
        acc += a
        if (i >= win) acc -= Math.abs(x[i - win])
        if (acc > best) { best = acc; bestAt = i - win / 2 }
      }
      // The loudest sample of the file as it plays (all channels, full bandwidth): what the audition table and the
      // "quiet file" rule use. The 8 kHz mono pass above is for timing only; it reads many files 10–40 dB too low.
      const probe = spawnSync('ffmpeg', ['-hide_banner', '-i', p, '-af', 'volumedetect', '-f', 'null', '-'], { encoding: 'utf8' })
      const hit = /max_volume:\s*(-?[\d.]+) dB/.exec(probe.stderr || '')
      table[path.relative(ROOT, p).replace(/\.mp3$/, '')] = {
        peakMs: Math.max(0, Math.round((bestAt / RATE) * 1000)),
        durationMs: Math.round((x.length / RATE) * 1000),
        peakDb: hit ? Math.round(Number(hit[1]) * 10) / 10 : Math.round(20 * Math.log10(peak || 1e-6) * 10) / 10,
      }
    }
  }
}
walk(ROOT)
const sorted = Object.fromEntries(Object.entries(table).sort(([a], [b]) => a.localeCompare(b)))
fs.writeFileSync(OUT, `// Generated by scripts/gen-sfx-peaks.mjs — do not edit by hand.\n/** Per sound effect (path under public/motion-studio/sfxlib, no extension): where it peaks (ms from its start), its length and its true loudest sample (dBFS, ffmpeg volumedetect). */\nexport const SFX_PEAKS: Record<string, { peakMs: number; durationMs: number; peakDb: number }> = ${JSON.stringify(sorted, null, 1)}\n`)
console.log(`sfx peaks: ${Object.keys(sorted).length} files`)
